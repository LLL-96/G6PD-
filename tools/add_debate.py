def main():
    data = json.load(open(SRC, encoding="utf-8"))
    items = data["items"] if isinstance(data, dict) else data
    by_name = {it["name"]: it for it in items}
    done, missing = [], []
    for name, txt in DEBATE.items():
        it = by_name.get(name)
        if not it:
            missing.append(name)
            continue
        it["debate"] = txt
        done.append(name)
    json.dump(data, open(SRC, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(f"已补分歧说明：{len(done)} 条")
    if missing:
        print("⚠ 库内未找到（跳过）：", missing)
    print("现有 debate 条目：", sum(1 for i in items if i.get("debate")),
          "；controversy 条目：", sum(1 for i in items if i.get("controversy")))


if __name__ == "__main__":
    main()
