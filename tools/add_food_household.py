#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""按类目补结构缺口（食物、生活用品、维生素）——回应"其他类目类似错误"。
原则：
- 蚕豆相关食物（粉丝/凉粉含蚕豆粉、酱油可能用蚕豆）→ caution，提醒看配料表；
- 含薄荷脑/樟脑的日用品（牙膏/漱口水/花露水/蚊香/空气清新剂）→ caution；
- 其余日常食物与用品 → safe（明确与 G6PD 溶血无关，消除不必要恐慌）。
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
F = os.path.join(ROOT, "data", "items.json")
d = json.load(open(F, encoding="utf-8"))
by_name = {i["name"]: i for i in d["items"]}

FOOD_SAFE = "与 G6PD（蚕豆病）溶血无明确关联，可正常食用。"
HOME_SAFE = "正常使用与 G6PD（蚕豆病）溶血无明确关联。"

added = 0
def add(name, cat, risk, summary, detail, note, aliases=None, controversy=False, sources=None):
    global added
    if name in by_name: 
        return False
    eid = "gap_" + re.sub(r"[^\w一-鿿]", "_", name)
    d["items"].append({
        "id": eid, "name": name, "risk": risk, "category": cat,
        "summary": summary, "detail": detail, "note": note,
        "controversy": controversy, "sources": sources or ["S1","S5"],
        "aliases": aliases or []
    })
    added += 1
    return True

# ============ 食物 ============
# 蚕豆相关（慎食，看配料表）
add("粉丝/凉粉", "food", "caution",
    "粉丝/凉粉一般用绿豆或红薯淀粉；但部分含蚕豆淀粉，G6PD 者需看配料表确认。",
    "安徽省卫健委提示：蚕豆粉可能存在于粉丝、凉粉中。纯绿豆/红薯粉丝可放心；购买/点餐时确认不含“蚕豆”成分。",
    "买前看配料表，确认未标“蚕豆”；不确定时少量或避免。", ["粉丝","凉粉","粉条","绿豆粉丝","红薯粉丝"])
add("酱油", "food", "safe",
    "普通大豆酱油不含蚕豆，可放心；少数地方用蚕豆酿造，需看配料表。",
    "安徽省卫健委明确：普通大豆酱油不含蚕豆，可放心使用；但购买前务必读配料表，确认未标“蚕豆”或“蚕豆制品”。",
    "买前扫一眼配料表；标“蚕豆酿造/蚕豆酱油”的避开。", ["生抽","老抽","豆酱油"])
# 含薄荷的食品（慎食）
add("薄荷糖/口香糖", "food", "caution",
    "薄荷糖、口香糖常含薄荷脑，按薄荷类处理，少量通常无碍。",
    "薄荷（薄荷脑）在部分资料中被列为 G6PD 需避免；含薄荷脑的糖果/口香糖少量含服一般问题不大，但避免大量、长期含服，尤其儿童。",
    "少量含服一般无碍；避免大量/长期含服。", ["薄荷糖","口香糖","薄荷口香糖","薄荷硬糖"])

# 常见食物（安全）
for nm, cls, al in [
    ("牛奶","牛奶/乳制品",["纯牛奶","乳制品","酸奶"]),
    ("鸡蛋","鸡蛋",["蛋清","蛋黄","鸡蛋羹"]),
    ("海鲜","海鲜",["鱼","虾","蟹","贝类","海鱼"]),
    ("花生","花生/坚果",["花生米","花生酱"]),
    ("坚果","坚果",["核桃","杏仁","腰果","开心果"]),
    ("巧克力","巧克力",["黑巧克力","牛奶巧克力"]),
    ("咖啡","咖啡",["拿铁","美式"]),
    ("茶","茶",["绿茶","红茶","乌龙茶"]),
    ("腐乳","腐乳",["豆腐乳","霉豆腐"]),
    ("豆芽","豆芽",["绿豆芽","黄豆芽"]),
    ("啤酒","啤酒",["适量饮酒"]),
    ("红酒","红酒",["葡萄酒"]),
    ("味精","调味品",["谷氨酸钠","鸡精"]),
    ("芥末","调味品",["黄芥末","青芥"]),
    ("芒果","水果",["芒果干"]),
    ("菠萝","水果",["凤梨"]),
    ("草莓","水果",[]),
    ("桑葚","水果",["桑椹"]),
    ("杨梅","水果",[]),
    ("樱桃","水果",["车厘子"]),
    ("石榴","水果",["石榴汁"]),
]:
    add(nm, "food", "safe",
        f"{nm}属{cls}，与 G6PD（蚕豆病）溶血无明确关联，可正常食用。",
        FOOD_SAFE + ("（芒果/菠萝等可能引起普通过敏，但那是过敏反应，与蚕豆病溶血无关。）" if nm in ("芒果","菠萝") else "")
        + ("（鸡蛋过敏是另一回事，与蚕豆病无关；本条目仅就 G6PD 溶血而言。）" if nm=="鸡蛋" else ""),
        "正常食用即可。", al)

# ============ 生活用品 ============
for nm, al in [
    ("洗衣液/洗衣粉", ["洗衣液","洗衣粉"]),
    ("洗洁精", ["洗洁精","洗碗液"]),
    ("漂白剂/84消毒液", ["84消毒液","漂白剂","含氯消毒液"]),
    ("香皂/沐浴露", ["香皂","肥皂","沐浴露"]),
    ("洗发水/护发素", ["洗发水","护发素","洗头水"]),
    ("化妆品", ["口红","粉底","眼影","化妆"]),
    ("香水", ["香水","香氛"]),
    ("面膜/护手霜/防晒霜", ["面膜","护手霜","防晒霜","护肤品"]),
    ("洗甲水/丙酮", ["洗甲水","丙酮","卸甲水"]),
    ("爽身粉", ["爽身粉","痱子粉"]),
]:
    add(nm, "household", "safe",
        f"{nm}为日常用品，{HOME_SAFE}",
        HOME_SAFE + "局部/日常接触不会引起 G6PD 溶血；注意勿误食、勿入眼。",
        "正常使用即可；避免误食、入眼。", al)

# 含薄荷脑/樟脑的日用品（慎食/慎用）
add("牙膏/漱口水", "household", "caution",
    "多数牙膏、漱口水含薄荷脑，按薄荷类处理；日常刷牙漱口用量小，通常无碍。",
    "薄荷脑在部分资料中被列为需避免；牙膏/漱口水含薄荷脑但每次用量很小、且多漱出，一般无需回避，儿童避免吞咽。",
    "按正常用量刷牙漱口，勿吞咽；对薄荷敏感者可换无薄荷配方。", ["牙膏","漱口水","薄荷牙膏"])
add("花露水/驱蚊液", "household", "caution",
    "花露水、部分驱蚊液含薄荷脑/樟脑/避蚊胺，属 G6PD 慎用类。",
    "花露水常含薄荷脑、樟脑等，部分资料列为 G6PD 需避免；大面积皮肤涂抹可经皮吸收。儿童、婴幼儿尤其慎用。",
    "少量局部使用；婴幼儿避免大面积涂抹；优先物理防蚊。", ["花露水","驱蚊液","驱蚊水","six god"])
add("蚊香/电蚊香", "household", "caution",
    "蚊香/电蚊香含拟除虫菊酯，部分樟脑型蚊香可能含萘或樟脑，G6PD 者建议慎用。",
    "普通拟除虫菊酯类蚊香正常使用风险低；但“樟脑型/含萘”蚊香需避免。房间应通风，婴幼儿避免长时间吸入。",
    "选拟除虫菊酯类、注意通风；避免“樟脑/含萘”型；婴幼儿优先蚊帐。", ["蚊香","电蚊香","盘蚊香","蚊香液"])
add("空气清新剂", "household", "caution",
    "部分空气清新剂含萘、对二氯苯或挥发性有机物，G6PD 者建议少用/不用。",
    "含“萘”“对二氯苯”的空气清新剂、防蛀块需避免；普通香氛类通风使用问题不大，但密闭空间长时间吸入不推荐。",
    "选成分简单的；避免含萘/对二氯苯产品；保持通风。", ["空气清新剂","固体清新剂","香薰蜡烛"])

# ============ 维生素缺口 ============
add("钙片", "vitamin", "safe",
    "钙片（碳酸钙/柠檬酸钙等）与 G6PD 溶血无明确关联，可正常补充。",
    "钙剂不在 G6PD 禁忌/慎用名单；按需补充即可（过量补钙另有其他问题，与蚕豆病无关）。",
    "按推荐剂量补充。", ["碳酸钙","柠檬酸钙","钙剂","葡萄糖酸钙片"])

d["meta"]["version"] = "0.2.1"
json.dump(d, open(F, "w", encoding="utf-8"), ensure_ascii=False, indent=2, sort_keys=False)
open(F, "a", encoding="utf-8").write("\n")
print(f"新增 {added} 条，版本 -> 0.2.1，总条目 {len(d['items'])}")
